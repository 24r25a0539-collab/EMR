for (const lang of Object.keys(extraTranslations)) {
  const dict = extraTranslations[lang];
  let snippet = `\n    // Expanded QA & Visual Upgrade Keys\n`;
  for (const [key, val] of Object.entries(dict)) {
    const escaped = val.replace(/'/g, "\\'");
    snippet += `    '${key}': '${escaped}',\n`;
  }

  // Insert before closing brace of lang
  const regex = new RegExp(`(${lang}:\\s*\\{[\\s\\S]*?)(\\n\\s*\\},)`);
  if (regex.test(content)) {
    content = content.replace(regex, `$1${snippet}  },`);
    console.log(`Successfully added ${Object.keys(dict).length} keys to ${lang}`);
  } else {
    console.error(`Failed to find closing block for ${lang}`);
  }
}

fs.writeFileSync(filePath, content, 'utf8');
